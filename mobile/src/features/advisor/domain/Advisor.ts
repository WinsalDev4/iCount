import type { CategoryId } from '@/core/domain/Category';
import type { Money } from '@/core/domain/Money';
import type { YearMonth } from '@/core/domain/YearMonth';

/** Applied with one tap through the existing use cases (budgets, debts, recurring). */
export type AdvisorAction =
  | {
      readonly type: 'set-budget';
      readonly categoryId: CategoryId;
      readonly month: YearMonth;
      readonly limit: Money;
    }
  | { readonly type: 'extra-debt-payment'; readonly debtId: string; readonly extraMonthly: Money }
  | { readonly type: 'cancel-recurring'; readonly recurringPaymentId: string };

export type InsightKind =
  'duplicate-subscription' | 'budget-exceeded' | 'expensive-debt' | 'unusual-spending' | 'other';

/** A figure from the household's data that backs an insight (never generated by the model). */
export interface Evidence {
  readonly label: string;
  readonly amount: Money;
}

export interface Insight {
  readonly id: string;
  readonly kind: InsightKind;
  /** 1 = most important. */
  readonly priority: number;
  readonly title: string;
  readonly body: string;
  readonly potentialMonthlySavings: Money | null;
  readonly evidence: readonly Evidence[];
  readonly actions: readonly AdvisorAction[];
}

export interface InsightsReport {
  readonly generatedAt: Date;
  readonly totalPotentialMonthlySavings: Money;
  readonly insights: readonly Insight[];
}

export interface PlanStep {
  readonly title: string;
  readonly detail: string;
  readonly action: AdvisorAction | null;
}

export interface Plan {
  readonly id: string;
  readonly kind: 'savings' | 'debt-payoff';
  readonly title: string;
  readonly summary: string;
  readonly steps: readonly PlanStep[];
  readonly projection: {
    readonly monthlySaving: Money | null;
    readonly interestSaved: Money | null;
    readonly debtFreeDate: Date | null;
  };
}

/** What the chat stream emits, in order: deltas and plans, then `done` or `error`. */
export type ChatEvent =
  | { readonly type: 'delta'; readonly text: string }
  | { readonly type: 'plan'; readonly plan: Plan }
  | {
      readonly type: 'done';
      readonly conversationId: string;
      readonly messageId: string;
      readonly remainingMessagesToday: number;
    }
  | { readonly type: 'error'; readonly message: string };

export interface AdvisorConsent {
  readonly granted: boolean;
  /** Version of the consent text; a newer version must be accepted again. */
  readonly version: number;
}
